export default async function FetchCSRF() {
    try {
        const response = await fetch('http://localhost:8000/index.php/csrf' , {
            method: 'GET',
            credentials: 'include'
        });
        const data = await response.json();
        return data.csrf_token;
    } catch (error) {
        console.error('Error fetching CSRF token:', error);
        return null;
    }
}
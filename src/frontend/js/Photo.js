/**
 * Simple Photo class based on the photo object returned by the server
 */
export default class Photo {
    constructor(photoData) {
        this.id = photoData.id;
        this.user_id = photoData.user_id;
        this.image_path = photoData.image_path;
        this.description = photoData.description ?? null;
        this.created_at = photoData.created_at ?? null;
    }
}

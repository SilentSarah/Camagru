class RouterHistory {

    constructor() {
        if (RouterHistory.instance)
            return RouterHistory.instance;

        this.index = 0;
        RouterHistory.instance = this;
    }

    increment() {
        this.index++;
    }

    decrement() {
        this.index--;
    }

    set(index) {
        this.index = index;
    }

    get() {
        return this.index;
    }
}

const routerHistory = new RouterHistory();
export default routerHistory;